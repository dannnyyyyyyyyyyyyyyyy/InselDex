const musikBesitzKey = "inseldex_musik_besitz_v1";
let musikBesitz = {};
try {
    musikBesitz = JSON.parse(localStorage.getItem(musikBesitzKey) || "{}");
} catch {
    musikBesitz = {};
}

function musikIstVorhanden(musik) { return !!musikBesitz[musik.id]; }
function speichereMusikBesitz() { localStorage.setItem(musikBesitzKey, JSON.stringify(musikBesitz)); }
function escMusik(value) {
    return String(value ?? "").replace(/[&<>"']/g, c => ({"&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;"}[c]));
}
function musikFortschritt() { return musikDaten.filter(musikIstVorhanden).length; }

function aktualisiereMusikProgress() {
    const vorhanden = musikFortschritt();
    const gesamt = musikDaten.length;

    const text = document.getElementById("musikFortschritt");
    if (text) text.textContent = `${vorhanden} / ${gesamt}`;

    const text2 = document.getElementById("musikFortschrittText");
    if (text2) text2.textContent = `${vorhanden} / ${gesamt}`;

    const balken = document.getElementById("musikFortschrittBalken");
    if (balken) balken.style.width = `${gesamt ? vorhanden / gesamt * 100 : 0}%`;

    const name = document.getElementById("musikMeilensteinName");
    const stufe = document.getElementById("musikMeilensteinText");
    const aktuell = document.getElementById("musikMeilensteinAktuell");
    const verlauf = document.getElementById("musikMeilensteinAbzeichen");
    const karte = aktuell?.closest(".musik-meilenstein");

    if (!name || !stufe || !aktuell || !verlauf) return;

    let index = 0;
    MUSIK_MEILENSTEINE.forEach((s, i) => {
        if (vorhanden >= s.schwelle) index = i;
    });

    const aktuelleStufe = MUSIK_MEILENSTEINE[index];
    const naechsteStufe = MUSIK_MEILENSTEINE[index + 1];

    name.textContent = aktuelleStufe.name;
    stufe.textContent = naechsteStufe
        ? `${vorhanden} / ${naechsteStufe.schwelle}`
        : `${vorhanden} / ${gesamt}`;

    const baueAbzeichen = (i) => {
        const stufeDaten = MUSIK_MEILENSTEINE[i];
        const item = document.createElement("div");
        item.className = "meilenstein-abzeichen-item";
        item.title = stufeDaten.name;
        const img = document.createElement("img");
        img.src = `./bilder/abzeichen/musik_stufe${i + 1}.png`;
        img.alt = `Abzeichen ${stufeDaten.name}`;
        item.appendChild(img);
        return item;
    };

    aktuell.innerHTML = "";
    const aktuellesBild = baueAbzeichen(index).querySelector("img").cloneNode(true);
    aktuellesBild.removeAttribute("title");
    const label = document.createElement("span");
    label.className = "meilenstein-abzeichen-stufe-aktuell";
    label.textContent = `Stufe ${index + 1} von ${MUSIK_MEILENSTEINE.length}`;
    aktuell.appendChild(aktuellesBild);
    aktuell.appendChild(label);

    verlauf.innerHTML = "";
    for (let i = 0; i <= index; i++) {
        verlauf.appendChild(baueAbzeichen(i));
    }

    karte?.classList.toggle(
        "meilenstein-max-stufe",
        index === MUSIK_MEILENSTEINE.length - 1
    );

    // Gemeinsames Erfolgssystem für das bereits vorhandene Glückwunsch-Popup.
    const stufen = MUSIK_MEILENSTEINE.map((s, i) => ({
        ab: s.schwelle,
        bis: MUSIK_MEILENSTEINE[i + 1]?.schwelle ?? gesamt,
        name: s.name
    }));
    pruefeMeilensteinErfolg("musik", vorhanden, stufen, "musik");
}


function baueMusikKarte(musik) {
    const vorhanden = musikIstVorhanden(musik);
    const karte = document.createElement("article");
    karte.className = `musik-karte ${vorhanden ? "vorhanden" : "offen"}`;
    karte.dataset.id = musik.id;
    const preis = musik.kaufpreis ? `${musik.kaufpreis.toLocaleString("de-DE")} Sternis` : "Unverkäuflich";
    karte.innerHTML = `
        <div class="musik-bild">
            <img src="${escMusik(musik.bild)}" alt="${escMusik(musik.name)}"
                 onerror="this.style.display='none'; this.nextElementSibling.style.display='flex';">
            <div class="musik-bild-platzhalter">🎵</div>
        </div>
        <h3>${escMusik(musik.name)}</h3>
        <div class="musik-original">${escMusik(musik.originalName)}</div>
        <div class="musik-tags"><span>${escMusik(musik.art)}</span><span>${escMusik(musik.groesse)}</span></div>
        <strong class="musik-preis">${preis}</strong>
        <div class="musik-quelle">${escMusik(musik.quelle)}</div>
        <button class="musik-status ${vorhanden ? "vorhanden" : ""}" type="button">${vorhanden ? "✓ Vorhanden" : "+ Noch nicht vorhanden"}</button>
    `;
    karte.querySelector(".musik-status").addEventListener("click", () => {
        if (musikIstVorhanden(musik)) delete musikBesitz[musik.id];
        else musikBesitz[musik.id] = true;
        speichereMusikBesitz();
        aktualisiereMusikProgress();
        zeigeMusik();
    });
    return karte;
}

function zeigeMusik() {
    const liste = document.getElementById("musikListe");
    if (!liste) return;
    const suche = (document.getElementById("musikSucheInput")?.value || "").trim().toLocaleLowerCase("de");
    const status = document.getElementById("musikStatusInput")?.value || "alle";
    const art = document.getElementById("musikArtInput")?.value || "alle";
    const gefiltert = musikDaten.filter(m => {
        const text = `${m.name} ${m.originalName}`.toLocaleLowerCase("de");
        if (suche && !text.includes(suche)) return false;
        if (status === "offen" && musikIstVorhanden(m)) return false;
        if (status === "vorhanden" && !musikIstVorhanden(m)) return false;
        if (art !== "alle" && m.art !== art) return false;
        return true;
    }).sort((a,b) => a.name.localeCompare(b.name, "de"));
    liste.innerHTML = "";
    if (!gefiltert.length) {
        liste.innerHTML = `<div class="musik-leer">Keine Musikstücke gefunden.</div>`;
        return;
    }
    gefiltert.forEach(m => liste.appendChild(baueMusikKarte(m)));
}

function initialisiereMusik() { aktualisiereMusikProgress(); zeigeMusik(); }

document.addEventListener("DOMContentLoaded", () => {
    ["musikSucheInput","musikStatusInput","musikArtInput"].forEach(id => {
        document.getElementById(id)?.addEventListener("input", zeigeMusik);
        document.getElementById(id)?.addEventListener("change", zeigeMusik);
    });
    document.getElementById("musikFilterReset")?.addEventListener("click", () => {
        document.getElementById("musikSucheInput").value = "";
        document.getElementById("musikStatusInput").value = "alle";
        document.getElementById("musikArtInput").value = "alle";
        zeigeMusik();
    });
    initialisiereMusik();
});
